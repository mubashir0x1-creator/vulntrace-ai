from pathlib import Path
import unittest
from unittest.mock import patch

import migrate_to_postgres as migration


class FakeCursor:
    def __init__(self, rows=()):
        self.rows = list(rows)

    def fetchall(self):
        return self.rows


class FakePostgresConnection:
    def __init__(self, table_names=()):
        self.table_names = list(table_names)
        self.statements = []
        self.rollback_count = 0

    def execute(self, query, params=()):
        self.statements.append((query, params))
        if "information_schema.tables" in query:
            return FakeCursor(
                {"table_name": name} for name in self.table_names
            )
        return FakeCursor()

    def rollback(self):
        self.rollback_count += 1


class MigrationPreflightTests(unittest.TestCase):
    def test_preflight_is_read_only_and_rolls_back(self):
        connection = FakePostgresConnection()

        result = migration.preflight_target(connection)

        self.assertEqual(result, [])
        self.assertEqual(
            connection.statements[0][0],
            "SET TRANSACTION READ ONLY",
        )
        self.assertEqual(connection.rollback_count, 1)

    def test_existing_vulntrace_table_blocks_before_opening_sqlite(self):
        connection = FakePostgresConnection(["users"])

        with patch("migrate_to_postgres._open_sqlite_read_only") as open_sqlite:
            with self.assertRaises(migration.TargetNotEmptyError) as raised:
                migration.migrate_sqlite_to_postgres(
                    connection,
                    sqlite_path=Path("not-opened.sqlite"),
                )

        self.assertEqual(raised.exception.tables, ("users",))
        open_sqlite.assert_not_called()

    def test_postgres_schema_contains_all_app_tables_and_identity_ids(self):
        schema = migration.SCHEMA_FILE.read_text(encoding="utf-8")

        for table in migration.TABLE_ORDER:
            self.assertIn(f"CREATE TABLE {table} (", schema)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", schema)
        self.assertIn("DEFERRABLE INITIALLY DEFERRED", schema)
        self.assertNotIn("CREATE TABLE IF NOT EXISTS", schema)

    def test_schema_script_splits_into_statements(self):
        schema = migration.SCHEMA_FILE.read_text(encoding="utf-8")

        statements = migration._sql_statements(schema)

        self.assertGreater(len(statements), len(migration.TABLE_ORDER))
        self.assertTrue(all(statement for statement in statements))


if __name__ == "__main__":
    unittest.main()
