-- PostgreSQL schema for VulnTrace AI.
-- Apply only through migrate_to_postgres.py after its empty-target check.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    source_format TEXT NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    severity TEXT NOT NULL,
    confidence DOUBLE PRECISION,
    description TEXT,
    evidence TEXT,
    asset TEXT,
    status TEXT NOT NULL DEFAULT 'open',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    evidence_quality DOUBLE PRECISION,
    risk_score DOUBLE PRECISION,
    duplicate_key TEXT,
    duplicate_of BIGINT REFERENCES findings(id) DEFERRABLE INITIALLY DEFERRED,
    duplicate_count INTEGER DEFAULT 0,
    verification_status TEXT NOT NULL DEFAULT 'not_started',
    verification_evidence TEXT,
    verified_at TIMESTAMP
);

CREATE TABLE analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES findings(id) ON DELETE CASCADE,
    analysis_type TEXT NOT NULL,
    content TEXT NOT NULL,
    source TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE remediation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES findings(id) ON DELETE CASCADE,
    recommendation TEXT NOT NULL,
    verification TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT NOT NULL REFERENCES findings(id) ON DELETE CASCADE,
    evidence TEXT NOT NULL,
    result TEXT NOT NULL DEFAULT 'NEEDS_REVIEW',
    ai_assessment TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reports_user_id ON reports(user_id);
CREATE INDEX idx_findings_report_id ON findings(report_id);
CREATE INDEX idx_findings_severity ON findings(severity);
CREATE INDEX idx_findings_duplicate_key ON findings(duplicate_key);
CREATE INDEX idx_findings_verification_status ON findings(verification_status);
CREATE INDEX idx_analyses_finding_id ON analyses(finding_id);
CREATE INDEX idx_analyses_finding_type_source
    ON analyses(finding_id, analysis_type, source);
CREATE INDEX idx_remediation_finding_id ON remediation(finding_id);
CREATE INDEX idx_verifications_finding_id ON verifications(finding_id);
